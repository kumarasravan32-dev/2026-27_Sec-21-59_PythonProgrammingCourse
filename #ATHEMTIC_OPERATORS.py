#arithmetic operators
num1=int(input("Enter the value of num1: "))
num2=int(input("enter the value of num2:"))
sum=num1+num2 #addition (+)
print("sum of the two numbers:",sum)

difference=num1-num2 #subtraction (-)
print("difference between two numbers:",difference)

product=num1*num2 #multiplication (*)
print("product between two numbers:",product)

division=num1/num2 #division (/)
print("division between two numbers:",division)

modulus=num1%num2 #modulus(%)
print("modulus between two numbers:",modulus)
floordivision=num1//num2 #floordivision(//)
print("floordivision between two numbers:",floordivision)

exponentiation=num1**num2 #exponentiation (**)
print("exponentiation between two numbers:",exponentiation)
